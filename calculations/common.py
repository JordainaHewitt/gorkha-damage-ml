"""
Shared settings for every figure and table script in the report.

Adapted from Jack Baker's paper template
(https://www.jackwbaker.com/advice/Paper_project_setup.html). Every script imports this module, so
formatting and output locations are set in one place. Change the style file or the paths here, rerun
make_all_figures.py, and every figure and table in the paper updates.

These scripts only PLOT. The heavy calculations are in ../scripts (01_baseline_rf.py ... 06_compare.py),
which write to ../results. Run those first; this folder reads their outputs.
"""

import os
import matplotlib.pyplot as plt

# --- Paths -----------------------------------------------------------------------------------------
calc_dir = os.path.dirname(os.path.abspath(__file__))
repo_dir = os.path.abspath(os.path.join(calc_dir, '..'))
results_dir = os.path.join(repo_dir, 'results')        # outputs of scripts/01..06

# The Overleaf project: paper.tex, references.bib, figures/, tables/.
# Default: the copy inside this repo (zip it and upload it to Overleaf).
paper_dir = os.path.join(repo_dir, 'paper')
# With Overleaf's Dropbox sync turned on, point this at the synced project instead, so new figures and
# tables go straight to Overleaf (Baker, "Connect your code to Overleaf"). For example:
# paper_dir = os.path.expanduser('~/Dropbox/Apps/Overleaf/Gorkha damage ML')

figure_dir = os.path.join(paper_dir, 'figures')
table_dir = os.path.join(paper_dir, 'tables')
os.makedirs(figure_dir, exist_ok=True)
os.makedirs(table_dir, exist_ok=True)

# --- Style -----------------------------------------------------------------------------------------
# One style file controls fonts, sizes, line widths, and colors for every figure.
plt.style.use(os.path.join(calc_dir, 'figure.mplstyle'))
plt.rcParams['font.size'] = 9
colors = plt.rcParams['axes.prop_cycle'].by_key()['color']
# Same colour for a model family in every figure
family_color = {'RF': colors[0], 'XGB': colors[1], 'MLP': colors[3], 'MLP plain': colors[2]}

# Width of the paper's text block, for full-width figures [inches] (letter paper, 0.75 in margins)
full_width = 7.3
# Width of one column in the two-column layout [inches]
column_width = 3.35


def save_figure(fig, name):
    """Save a figure to the paper's figures folder as a PDF."""
    fig.savefig(os.path.join(figure_dir, name + '.pdf'))
    plt.close(fig)


def save_table(text, name):
    """Save LaTeX table code to the paper's tables folder; paper.tex reads it with \\input{tables/name}."""
    with open(os.path.join(table_dir, name + '.tex'), 'w') as f:
        f.write('% Generated by calculations/' + name + ' script. Do not edit by hand.\n' + text)


def result(*parts):
    """Path to a file in ../results."""
    return os.path.join(results_dir, *parts)


def script_settings(name):
    """Values from the SETTINGS block at the top of ../scripts/<name>, without running the script
    (so reading the MLP settings does not need torch)."""
    from pathlib import Path
    src = open(os.path.join(repo_dir, 'scripts', name)).read()
    start = src.index('# ---------------- SETTINGS')
    end = src.index('# ------------------------------------------', start + 40)
    ns = {'ROOT': Path(repo_dir), 'Path': Path}
    exec(src[start:end], ns)
    return ns
